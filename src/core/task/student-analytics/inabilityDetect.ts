/**
 * 【P6/T9】b+c 服从流程的两个纯函数判定。
 *
 * 为什么单独一个模块：与 `demandDetect` 同一角色 —— 判定必须可单测、可复盘。
 *
 * ⚠️ **判定口径**（【P6/T9 fix F3-①】登记，勿再声称"宁漏勿误"）：
 * `我不懂…` / `我看不懂…` 这类**理解性提问**同样命中（brief 的测试明文要求 `我看不懂这段 → true`）——
 * 学生会先看到一次"你是希望我直接给出完整实现吗？"的询问。这是**产品裁定**
 * （宁可多问一次：学生答"不是"即落 `denied` 回引导态，代价只是多一步确认；收益是不漏掉真正的"写不出来"），
 * 不是判定实现偏离。另一半仍偏保守：`我写一个…` / `请提供完整实现` 这类**索要**不算自述能力不足。
 */

/**
 * 「我写不出来」类自述。
 *
 * 【P7/T1（裁定 1 = A+B）】**实测输入的检测面是判定的一部分，不是实现细节**：
 * 2026-10-18 的 F5 实测里学生说「即使这样我还是**无法理解**，直接把完整代码给我」，
 * 旧模式（只认 `我不会/不懂/写不出来` 与 `我看不懂`）一句都没命中 ⇒ b+c 询问一次也没发生，
 * M6'' 完全跑不起来。因此按裁定同时做两件事：
 *   A. 扩充口语 / 放弃类自述；
 *   B. 增加「无法/不能 + 理解类动词」的组合判定（不要求第一人称）。
 *
 * ⚠️ 扩充的同时必须防反向误判（同样是实测语料）：
 *   - `我不会放弃的` —— `不会` 后面跟的是坚持，不是能力不足 ⇒ 用否定前瞻排除；
 *   - `这题不难理解` —— 否定的是"难"，不是能力 ⇒ 组合判定只认 `无法/不能`；
 *   - `直接把完整代码给我` —— 索要 ≠ 自述写不出来，绝不能触发询问。
 */
const INABILITY_PATTERNS: readonly RegExp[] = [
	// —— 原有：第一人称能力 / 理解自述（`不会` 加否定前瞻，见上）——
	/我(?:真的|确实|实在|完全)?(?:不会(?!放弃|再试|停下|认输|输)|不懂|写不出来|写不出|想不出来|想不到|没思路|没有思路)/,
	/我(?:实在|真的)?(?:写|做|编|拼)不(?:出来|出)/,
	// 「照着/按着写也写不出来」及其省略「着」的口语形态「照抄也写不出来」
	/(?:照|按)着?(?:写|抄)也(?:写|做)不(?:出来|出)/,
	// 【P8/T4】「我还是写不出来」—— 2026-10-18 实测漏判的正是它（旧模式只允许「实在/真的」）
	/我(?:真的|实在|还是|仍然|依然|始终)?(?:写|做|编|拼)不(?:出来|出)/,
	/我看不懂/,
	/(?:你)?(?:就)?别问了/,
	// —— 【P7/T1-A】扩充：口语化 / 放弃类自述（仍要求第一人称）——
	/我(?:真的|确实|实在|完全|还是|仍然|始终)?(?:搞不定|弄不明白|理解不了|学不会|没学会|不会写|写不了|看不懂|听不明白)/,
	/我(?:完全|根本|基本)?没(?:有)?(?:头绪|思路)/,
	/我(?:已经)?(?:想|打算|准备)?放弃了?/,
	// —— 【P7/T1-B】组合判定：无法 / 不能 + 理解类动词（不要求第一人称）——
	/(?:无法|不能|没法|没办法)(?:理解|搞懂|看懂|想明白|弄明白|掌握)/,
	/(?:还是|仍然|依然|始终|真的|完全)(?:不懂|不理解|没搞懂|没看懂)/,
	// —— 【P7/T1-B】不带主语的通用理解失败 ——
	/(?:搞|弄)(?:不|没)明白/,
	/(?:看|听)不懂/,
]

/** 肯定答复（保守：只认整句肯定，避免"不是/先不要"被误判） */
const AFFIRMATION_PATTERNS: readonly RegExp[] = [
	/^(?:是|是的|对|对的|好|好的|行|可以|要|嗯|就这样|给我|请给|直接给)[。！!，,～~、\s]{0,4}$/,
	/^(?:可以|好的|行)[，,].{0,8}$/,
]

export function isInabilityStatement(text: string | undefined): boolean {
	const t = (text ?? "").trim()
	if (!t) {
		return false
	}
	return INABILITY_PATTERNS.some((re) => re.test(t))
}

export function isAffirmation(text: string | undefined): boolean {
	const t = (text ?? "").trim()
	if (!t) {
		return false
	}
	return AFFIRMATION_PATTERNS.some((re) => re.test(t))
}
