/**
 * 【P5/T16】「索要完整实现」的判定（纯函数，无副作用）。
 *
 * 为什么单独一个模块：实测（M6'/M11'）表明，学生在**概念型任务**里直接索要完整实现时，
 * `rulePolicy` 会把代码类规则整体停用 ⇒ 这个行为**没有任何可计数、可升级的规则**，
 * 只剩一句提示词约束，模型一给就是完整实现、也永远不会被干预。
 *
 * 本判定只看**学生原文**（不看分类），因此对 `algorithm` / `explanation` / `other` 一视同仁 ——
 * 与「概念护栏的任务级粘性」一致：索要完整实现只会被计数，不会撤销护栏。
 */

/** 「完整实现」类索要的典型句式（实测样本 + 常见变体，刻意保守：宁可漏判也不误判） */
const DEMAND_PATTERNS: readonly RegExp[] = [
	/完整(?:的)?(?:代码|实现|程序|版本|版|答案)/,
	/**
	 * ★ M4' 的**原句**形态：「帮我写一个完整的冒泡排序程序」。
	 * 上面那条要求「完整」与「程序/代码」**紧邻**，因此漏掉了本形态（"完整的" 与 "程序" 之间隔着主题词）。
	 * 本式允许两词之间最多 12 个非断句字符，动词表刻意限制为"要一份东西"的那几个，
	 * 并**必须**以代码类名词收尾（"写一个完整的思路/解释" 不匹配）。
	 */
	/(?:写|给|做|实现|输出|生成|来|提供)(?:出|我)?(?:一)?(?:个|份|版|套)?(?:完整|全部|整个)(?:的)?[^。！？\n]{0,12}?(?:代码|实现|程序|答案|版本)/,
	/全部(?:的)?(?:代码|实现)/,
	/全套(?:的)?代码/,
	/可运行(?:的)?(?:代码|程序|实现)/,
	/(?:直接|干脆|就)(?:把|给|发|写)(?:我)?(?:一份|一个|个)?(?:完整|全部)?(?:的)?(?:代码|实现|程序)/,
	/(?:把|给|发)(?:完整|全部|整个)?(?:的)?(?:代码|实现|程序)(?:给|发)(?:我|过来)/,
	/不要(?:再)?(?:解释|讲解|废话|讲原理)/,
	/直接(?:给我|贴出|输出)(?:答案|结果|代码)/,
	/我要(?:完整|全部)?(?:的)?(?:代码|实现|答案)/,
]

/**
 * 该学生文本是否在索要「完整实现」。
 *
 * @param text 学生原文（`rawContent`；缺失时返回 false —— 不臆造）
 */
export function isCompleteImplDemand(text: string | undefined): boolean {
	const t = (text ?? "").trim()
	if (!t) {
		return false
	}
	return DEMAND_PATTERNS.some((re) => re.test(t))
}
